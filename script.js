function initPuzzle() {
    const board = document.getElementById('puzzle-board');
    let selectedPiece = null;
    const order = ['p1', 'p2', 'p3', 'p4'];
    function shuffle() {
        const pieces = Array.from(board.querySelectorAll('.puzzle-piece'));
        for (let i = pieces.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            board.appendChild(pieces[j]);
        }
    }
    shuffle();
    board.addEventListener('click', e => {
        const piece = e.target.closest('.puzzle-piece');
        if (!piece) return;
        AudioEngine.click();
        if (!selectedPiece) {
            selectedPiece = piece;
            piece.style.outline = '2px solid var(--accent)';
            piece.style.transform = 'scale(0.95)';
        } else if (selectedPiece === piece) {
            selectedPiece.style.outline = 'none'; selectedPiece.style.transform = 'none'; selectedPiece = null;
        } else {
            const nextSibling = piece.nextSibling === selectedPiece ? piece : piece.nextSibling;
            board.insertBefore(piece, selectedPiece); board.insertBefore(selectedPiece, nextSibling);
            selectedPiece.style.outline = 'none'; selectedPiece.style.transform = 'none'; selectedPiece = null;
            checkPuzzle();
        }
    });
    function checkPuzzle() {
        const currentOrder = Array.from(board.querySelectorAll('.puzzle-piece')).map(p => p.id);
        if (currentOrder.every((val, index) => val === order[index])) {
            unlockAchievement('puzzle'); logSystem("PUZZLE_STABILIZED: Order restored."); board.style.border = '2px solid #0f0';
        }
    }
    document.getElementById('puzzle-reset').addEventListener('click', () => { AudioEngine.click(); shuffle(); board.style.border = '1px dashed var(--border)'; });
}

