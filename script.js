const bgCanvas = document.getElementById('bg-canvas');
const bgCtx = bgCanvas ? bgCanvas.getContext('2d') : null;
let nodes = [];
function initBg() {
    if (!bgCanvas) return;
    bgCanvas.width = window.innerWidth; bgCanvas.height = window.innerHeight;
    nodes = []; const count = Math.floor((window.innerWidth * window.innerHeight) / 8000);
    for (let i = 0; i < count; i++) {
        nodes.push({ x: Math.random() * bgCanvas.width, y: Math.random() * bgCanvas.height, vx: (Math.random() - 0.5) * 0.4, vy: (Math.random() - 0.5) * 0.4, baseRadius: Math.random() * 2 + 1, currentRadius: 1 });
    }
}
function drawBg() {
    if (!bgCanvas) return;
    bgCtx.clearRect(0, 0, bgCanvas.width, bgCanvas.height);
    nodes.forEach((node, i) => {
        if (mouse.x) {
            const dx = mouse.x - node.x; const dy = mouse.y - node.y; const dist = Math.hypot(dx, dy);
            if (dist < 300) { node.x += dx * 0.001; node.y += dy * 0.001; node.currentRadius = node.baseRadius * (1 + (1 - dist / 300) * 1.5); }
            else { node.currentRadius = node.baseRadius; }
        }
        node.x += node.vx; node.y += node.vy;
        if (node.x < 0 || node.x > bgCanvas.width) node.vx *= -1;
        if (node.y < 0 || node.y > bgCanvas.height) node.vy *= -1;
        bgCtx.fillStyle = mouse.x && Math.hypot(node.x - mouse.x, node.y - mouse.y) < 250 ? 'rgba(59, 130, 246, 0.9)' : 'rgba(59, 130, 246, 0.6)';
        bgCtx.beginPath(); bgCtx.arc(node.x, node.y, node.currentRadius, 0, Math.PI * 2); bgCtx.fill();
        for (let j = i + 1; j < nodes.length; j++) {
            const next = nodes[j]; const dist = Math.hypot(node.x - next.x, node.y - next.y);
            if (dist < 150) { bgCtx.lineWidth = 0.5 * (1 - dist / 150); bgCtx.strokeStyle = `rgba(59, 130, 246, ${0.4 * (1 - dist / 150)})`; bgCtx.beginPath(); bgCtx.moveTo(node.x, node.y); bgCtx.lineTo(next.x, next.y); bgCtx.stroke(); }
        }
    });
    requestAnimationFrame(drawBg);
}
